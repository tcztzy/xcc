def guard_allocation_calls(text: str) -> str:
    return text.replace(
        "call ptr @malloc(",
        "call ptr @__xcc_aot_alloc(",
    ).replace(
        "call ptr @calloc(",
        "call ptr @__xcc_aot_calloc(",
    )


